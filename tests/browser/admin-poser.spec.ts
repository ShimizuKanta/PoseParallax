import { test, expect } from '@playwright/test';

test('host PC participates in another tab while admin fixes and changes the poser', async ({ browser }, info) => {
  const host = await browser.newContext({baseURL:'http://127.0.0.1:8011',viewport:{width:1280,height:900}});
  const guest = await browser.newContext({baseURL:'http://127.0.0.1:8011',viewport:{width:390,height:844}});
  const admin = await host.newPage(), observer = await guest.newPage();
  const errors: string[] = [];
  admin.on('pageerror',error=>errors.push(error.message));
  try {
    await admin.goto('/admin');
    await admin.getByLabel('管理者パスワード').fill('browser-test-password');
    await admin.getByRole('button',{name:'ログイン',exact:true}).click();
    await expect(admin.getByLabel('ポーズ役の選び方')).toHaveValue('');
    await admin.getByText('このPCでポーズ役として参加',{exact:true}).click();
    await admin.getByLabel('このPCの表示名').fill('司会PC');
    await admin.getByRole('button',{name:'このPCを参加させてポーズ役に固定',exact:true}).click();
    const link = admin.getByRole('link',{name:'このPCの参加画面を開く',exact:true});
    await expect(link).toBeVisible();
    const state = await (await host.request.get('/api/state')).json();
    expect(state.admin).toBe(true);
    expect(state.admin_player_id).toBe(state.fixed_poser_id);
    await expect(admin.getByLabel('ポーズ役の選び方')).toHaveValue(state.admin_player_id);
    const popupPromise = host.waitForEvent('page');
    await link.click();
    const pc = await popupPromise;
    pc.on('pageerror',error=>errors.push(error.message));
    await expect(pc.getByRole('heading',{name:'仲間を待っています'})).toBeVisible();
    expect((await (await host.request.get('/api/state?participant=1')).json()).admin).toBe(false);
    await observer.goto('/');
    await observer.getByLabel('表示名').fill('観察者');
    await observer.getByRole('button',{name:'参加する'}).click();
    await expect(admin.locator('#member-count')).toHaveText('2 / 50人');
    await admin.getByRole('button',{name:'ゲームを準備',exact:true}).click();
    await expect(pc.getByRole('heading',{name:'あなたがポーズ役'})).toBeVisible();
    await expect(pc.locator('#poser-view canvas')).toBeVisible();
    await pc.getByRole('button',{name:'ポーズの準備完了',exact:true}).click();
    await observer.getByRole('button',{name:'カメラを起動 / 再試行',exact:true}).click();
    await expect(observer.getByRole('button',{name:'カメラの準備完了',exact:true})).toBeEnabled({timeout:60000});
    await observer.getByRole('button',{name:'カメラの準備完了',exact:true}).click();
    await expect(admin.getByRole('button',{name:'ラウンド開始',exact:true})).toBeEnabled();
    await admin.getByRole('button',{name:'ラウンド開始',exact:true}).click();
    await expect(pc.locator('#ready-button')).toBeHidden();
    await expect(admin.locator('#admin-round-status')).toContainText('司会PC');
    await admin.screenshot({path:info.outputPath('admin-pc-poser.png'),fullPage:true});
    await pc.reload();
    await expect(pc.getByRole('heading',{name:'あなたがポーズ役'})).toBeVisible();
    await expect(admin.getByRole('heading',{name:'ゲーム進行'})).toBeVisible();
    const observerId = (await (await guest.request.get('/api/state')).json()).me;
    await admin.getByLabel('ポーズ役の選び方').selectOption(observerId);
    await expect.poll(async()=> (await (await host.request.get('/api/state')).json()).fixed_poser_id).toBe(observerId);
    expect((await (await host.request.get('/api/state')).json()).round.poser_id).toBe(state.admin_player_id);
    admin.once('dialog',dialog=>dialog.accept());
    await admin.getByRole('button',{name:'スキップ',exact:true}).click();
    await admin.getByRole('button',{name:'次のラウンドを準備',exact:true}).click();
    await expect(observer.getByRole('heading',{name:'あなたがポーズ役'})).toBeVisible();
    await admin.getByLabel('Language / 言語').selectOption('en');
    await expect(admin.getByLabel('Poser selection')).toHaveValue(observerId);
    await admin.getByLabel('Poser selection').selectOption('');
    await expect.poll(async()=> (await (await host.request.get('/api/state')).json()).fixed_poser_id).toBeNull();
    admin.once('dialog',dialog=>dialog.accept());
    await admin.getByRole('button',{name:'End game',exact:true}).click();
    admin.once('dialog',dialog=>dialog.accept('Pose Parallax'));
    await admin.getByRole('button',{name:'Register next group',exact:true}).click();
    await expect(admin.locator('#member-count')).toHaveText('0 / 50 participants');
    expect(errors).toEqual([]);
  } finally { await host.close(); await guest.close(); }
});
